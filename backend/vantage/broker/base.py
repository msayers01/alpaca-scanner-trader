"""Broker + market-data protocol. Implemented by AlpacaBroker (paper/live) and SimBroker (sim).

All methods return *normalised* plain dicts / domain types so the rest of the system never sees
provider-specific payloads. Shapes follow docs/API.md (Account, Position, Order).
"""

from __future__ import annotations

from datetime import date
from typing import Any, Protocol

from vantage.core.types import Bar, NewsItem, OptionContract, Quote


class Broker(Protocol):
    mode: str
    stock_feed: str
    options_feed: str

    async def start(self) -> None: ...
    async def stop(self) -> None: ...

    # --- trading
    async def get_account(self) -> dict[str, Any]: ...
    async def get_positions(self) -> list[dict[str, Any]]: ...
    async def get_orders(self, status: str = "open", limit: int = 100) -> list[dict[str, Any]]: ...
    async def get_order(self, order_id: str) -> dict[str, Any]: ...
    async def submit_order(self, req: dict[str, Any]) -> dict[str, Any]: ...
    async def replace_order(
        self, order_id: str, limit_price: float | None = None, qty: float | None = None
    ) -> dict[str, Any]: ...
    async def cancel_order(self, order_id: str) -> None: ...
    async def close_position(self, symbol: str, pct: float = 1.0) -> dict[str, Any]: ...
    async def get_portfolio_history(self, rng: str) -> dict[str, Any]: ...
    async def get_calendar(self, start: date, end: date) -> list[dict[str, Any]]: ...

    # --- market data
    async def get_bars(
        self, symbol: str, timeframe: str, start_ms: int, end_ms: int | None = None, limit: int = 10000
    ) -> list[Bar]: ...
    async def get_bars_multi(
        self, symbols: list[str], timeframe: str, start_ms: int, end_ms: int | None = None
    ) -> dict[str, list[Bar]]: ...
    async def get_snapshots(self, symbols: list[str]) -> dict[str, dict[str, Any]]: ...
    async def get_option_expirations(self, underlying: str) -> list[date]: ...
    async def get_option_chain(
        self, underlying: str, exp_gte: date | None = None, exp_lte: date | None = None
    ) -> list[OptionContract]: ...
    async def get_option_bars(
        self, symbol: str, timeframe: str, start_ms: int, end_ms: int | None = None
    ) -> list[Bar]: ...
    async def get_news(self, symbols: list[str] | None, limit: int = 50) -> list[NewsItem]: ...
    async def search_assets(self, q: str) -> list[dict[str, Any]]: ...
    async def get_most_actives(self, top: int = 20) -> list[str]: ...

    # --- streaming (implementations publish onto the Bus)
    async def stream_subscribe(
        self, quotes: list[str] = (), bars: list[str] = (), trades: list[str] = ()
    ) -> None: ...
    async def stream_unsubscribe(
        self, quotes: list[str] = (), bars: list[str] = (), trades: list[str] = ()
    ) -> None: ...
    async def options_subscribe(self, quotes: list[str] = (), trades: list[str] = ()) -> None: ...
    async def options_unsubscribe(self, quotes: list[str] = (), trades: list[str] = ()) -> None: ...
    def connection_state(self) -> dict[str, bool]: ...


class BrokerError(Exception):
    def __init__(self, message: str, status: int | None = None, code: str | None = None):
        super().__init__(message)
        self.status = status
        self.code = code


def latest_quote_from_snapshot(sym: str, snap: dict[str, Any]) -> Quote | None:
    q = snap.get("quote")
    return q if isinstance(q, Quote) else None
